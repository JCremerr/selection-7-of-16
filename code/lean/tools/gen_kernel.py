#!/usr/bin/env python3
"""Generate Selection/Kernel.lean: run the checker on the certificate inside
Lean's kernel (`decide +kernel`), in chunks of C functions, and glue the chunks.

Usage: python3 -I tools/gen_kernel.py NFUNS N RANK W [--chunk C] [--out FILE]
           [--ns NS --cert-module M --hints-module M] [--fast K]
--fast K: the data was written by rs2lean.py --parts K (blocks funs_parts /
hints_parts); the chunks then run `checkFnL` with the two-level lookup of
Selection/Fast.lean, and `all_checkFn_of_fast` turns that into `checkFn`.
Not trusted: Lean checks every generated theorem.
"""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("nfuns", type=int)
ap.add_argument("n", type=int)
ap.add_argument("rank", type=int)
ap.add_argument("w", type=int)
ap.add_argument("--chunk", type=int, default=10)
ap.add_argument("--out", default="Selection/Kernel.lean")
ap.add_argument("--ns", default="Cert", help="namespace Sel.NS of prog/hints")
ap.add_argument("--cert-module", default="Selection.Cert")
ap.add_argument("--hints-module", default="Selection.Hints")
ap.add_argument("--fast", type=int, default=None, help="block size K of the data (rs2lean --parts K)")
a = ap.parse_args()

N, C = a.nfuns, a.chunk
starts = list(range(0, N, C))
P = "checkFn prog hints" if a.fast is None else \
    f"checkFnL (look2 {a.fast} funs_parts) (look2 {a.fast} hints_parts)"
L = []
if a.fast is None:
    L.append(f"import {a.cert_module}\nimport {a.hints_module}\n")
    how = ""
else:
    L.append(f"import {a.cert_module}\nimport {a.hints_module}\nimport Selection.Fast\n")
    how = f"""
    Table lookups use the two-level lookup `look2 {a.fast}` over the blocks
    `funs_parts` / `hints_parts` (Selection/Fast.lean, proved equal to the
    plain array lookups)."""
L.append(f"""/-! GENERATED by tools/gen_kernel.py ({N} functions, chunks of {C}).
    Runs the checker `checkFn` on every function of the certificate inside
    Lean's KERNEL (`decide +kernel`: kernel reduction only, no compiler or
    native code in the trust base), then glues the chunks into
    `check prog hints {a.n} {a.rank} {a.w} = true`.{how} -/

namespace Sel.{a.ns}
open Sel

theorem all_range'_glue {{p : Nat → Bool}} (s m n s' t : Nat) (hs : s + m = s') (ht : m + n = t)
    (h1 : (List.range' s m).all p = true) (h2 : (List.range' s' n).all p = true) :
    (List.range' s t).all p = true := by
  subst hs ht
  rw [← List.range'_append, List.all_append, h1, Nat.one_mul, h2]; rfl
""")
for k, s in enumerate(starts):
    c = min(C, N - s)
    L.append(f"theorem chunk_{k} : (List.range' {s} {c}).all ({P}) = true := by decide +kernel")
L.append("")
last = len(starts) - 1
for k in range(last, -1, -1):
    s = starts[k]
    rest = N - s
    if k == last:
        L.append(f"theorem upto_{k} : (List.range' {s} {rest}).all ({P}) = true := chunk_{k}")
    else:
        c = starts[k + 1] - s
        L.append(f"theorem upto_{k} : (List.range' {s} {rest}).all ({P}) = true :=\n"
                 f"  all_range'_glue {s} {c} {rest - c} {s + c} {rest} rfl rfl chunk_{k} upto_{k+1}")
L.append(f"""
theorem funs_size : prog.funs.size = {N} := by decide +kernel
""")
if a.fast is None:
    L.append(f"""theorem check_ok : check prog hints {a.n} {a.rank} {a.w} = true := by
  unfold check
  rw [funs_size, List.range_eq_range', upto_0, Bool.true_and]
  decide +kernel

end Sel.{a.ns}
""")
else:
    K = a.fast
    L.append(f"""theorem uniform_funs : uniform {K} funs_parts = true := by decide +kernel
theorem uniform_hints : uniform {K} hints_parts = true := by decide +kernel

theorem all_ok : (List.range {N}).all (checkFn prog hints) = true :=
  all_checkFn_of_fast prog hints {K} funs_parts hints_parts rfl rfl uniform_funs uniform_hints {N}
    (by rw [List.range_eq_range']; exact upto_0)

theorem check_ok : check prog hints {a.n} {a.rank} {a.w} = true := by
  unfold check
  rw [funs_size, all_ok, Bool.true_and]
  decide +kernel

end Sel.{a.ns}
""")
open(a.out, "w").write("\n".join(L))
print(f"gen_kernel: wrote {a.out}: {len(starts)} chunks")
